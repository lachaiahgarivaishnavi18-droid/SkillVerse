import 'dart:io';

import 'package:learning_app/data/app_content.dart';
import 'package:learning_app/data/course_models.dart';

String sql(String value) => "'${value.replaceAll("'", "''")}'";

void main() {
  final answers = <(String, String), int?>{};
  void add(String source, QuizQuestion question) {
    final key = (source, question.id);
    if (answers.containsKey(key) && answers[key] != question.answerIndex) {
      throw StateError('Conflicting answer keys for $key');
    }
    answers[key] = question.answerIndex;
  }

  for (final question in quizQuestions) {
    add('quiz', question);
  }
  for (final course in courses) {
    for (final question in course.finalQuestions) {
      add('assessment', question);
    }
    for (final module in course.modules) {
      for (final question in module.moduleQuizQuestions) {
        add('quiz', question);
      }
    }
  }
  for (final question in interviewQuestions) {
    answers[('mock_interview', question.id)] = null;
  }

  stdout.writeln(
    '-- Generated by dart run tool/export_leaderboard_catalog.dart',
  );
  stdout.writeln(
    'insert into public.skillverse_scoring_catalog '
    '(source, question_id, answer_index) values',
  );
  stdout.writeln(
    answers.entries
        .map((entry) {
          final (source, id) = entry.key;
          return '  (${sql(source)}, ${sql(id)}, ${entry.value ?? 'null'})';
        })
        .join(',\n'),
  );
  stdout.writeln(
    'on conflict (source, question_id) do update '
    'set answer_index = excluded.answer_index;',
  );
}
